import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';

test('supplied Home design filters real catalog by city, budget and bedrooms', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByTestId('apartment-card').first()).toBeVisible();
  await expect(page.getByRole('link', { name: 'Đăng nhập', exact: true })).toHaveAttribute('href', '/login');
  await expect(page.getByRole('link', { name: 'Đăng ký', exact: true })).toHaveAttribute('href', '/register');
  await expect(page.locator('.home-city')).toHaveCount(4);
  const cityResponse = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('city') === 'TP. Hồ Chí Minh');
  await page.getByRole('button', { name: 'Tìm căn hộ tại TP.HCM', exact: true }).click();
  expect((await cityResponse).status()).toBe(200);
  await expect(page.getByLabel('Tỉnh / Thành phố', { exact: true })).toHaveValue('TP. Hồ Chí Minh');
  await expect(page.getByLabel('Quận / Huyện / Khu vực')).toHaveValue('');
  const catalog = await (await page.request.get('/api/v1/apartments?city=TP.%20H%E1%BB%93%20Ch%C3%AD%20Minh&size=100')).json();
  expect(catalog.items.length).toBeGreaterThan(0);
  const selected = catalog.items[0];
  await page.getByLabel('Giá tối thiểu / tháng').fill(selected.advertisedMonthlyRent);
  await page.getByLabel('Giá tối đa / tháng').fill(selected.advertisedMonthlyRent);
  await page.getByLabel('Số phòng ngủ').selectOption(String(selected.bedrooms));
  const filtered = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.has('bedrooms'));
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  const result = await filtered;expect(result.status()).toBe(200);const body = await result.json();
  const expected = catalog.items.filter((a: typeof selected) => a.bedrooms === selected.bedrooms && a.advertisedMonthlyRent === selected.advertisedMonthlyRent);
  expect(body.totalElements).toBe(expected.length);
  await expect(page.getByTestId('apartment-card')).toHaveCount(Math.min(6,expected.length));
  const bedroomOnly = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('bedrooms') === '5');
  await page.getByLabel('Số phòng ngủ').selectOption('5');await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();expect((await bedroomOnly).status()).toBe(200);
  await page.getByLabel('Giá tối thiểu / tháng').fill('99999999');
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Giá tối thiểu phải nhỏ hơn');
  await page.getByLabel('Giá tối thiểu / tháng').fill('');await page.getByLabel('Giá tối đa / tháng').fill('');
  const absent = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('city')?.includes('Đà Nẵng') === true);
  await page.getByRole('button', { name: 'Tìm căn hộ tại Đà Nẵng', exact: true }).click();
  const absentData = await (await absent).json();
  await expect(page.getByLabel('Tỉnh / Thành phố', { exact: true })).toHaveValue('TP. Đà Nẵng');
  if (absentData.totalElements === 0) await expect(page.getByRole('heading', { name: 'Chưa có căn hộ phù hợp' })).toBeVisible();
  const missingCity = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('city') === 'Bình Dương');
  await page.getByRole('button', { name: 'Tìm căn hộ tại Bình Dương', exact: true }).click();expect((await missingCity).status()).toBe(200);
  await expect(page.getByLabel('Tỉnh / Thành phố', { exact: true })).toHaveValue('Bình Dương');
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).first().click();
  await expect(page.getByLabel('Số phòng ngủ')).toHaveValue('');await expect(page.getByLabel('Tỉnh / Thành phố', { exact: true })).toHaveValue('');
  await expect(page.getByTestId('apartment-card').first()).toBeVisible();
  const options = await (await page.request.get('/api/v1/apartments/address-options')).json();
  const address = options.find((o: { city: string; ward: string | null }) => o.city === 'TP. Hồ Chí Minh' && o.ward);
  expect(address).toBeTruthy();await page.getByLabel('Tỉnh / Thành phố', { exact: true }).selectOption(address.city);
  await page.getByLabel('Quận / Huyện / Khu vực').selectOption(address.district);await page.getByLabel('Phường / Xã').selectOption(address.ward);
  const wardResponse = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('ward') === address.ward);
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();expect((await wardResponse).status()).toBe(200);
  await page.getByRole('button', { name: 'Tìm căn hộ tại Đà Nẵng', exact: true }).click();
  await expect(page.getByLabel('Quận / Huyện / Khu vực')).toHaveValue('');await expect(page.getByLabel('Phường / Xã')).toHaveValue('');
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).first().click();await expect(page.getByTestId('apartment-card').first()).toBeVisible();
  if (catalog.totalElements > 6) {
    const nextPage = page.waitForResponse(response => response.url().includes('/api/v1/apartments?') && new URL(response.url()).searchParams.get('page') === '1');
    await page.getByRole('button', { name: 'Trang sau', exact: true }).click();expect((await nextPage).status()).toBe(200);
    await page.getByRole('button', { name: 'Tìm căn hộ tại TP.HCM', exact: true }).click();await expect(page.getByText('Trang 1 / 2', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).first().click();
  }
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
  mkdirSync('test-results/visual', { recursive: true });await page.screenshot({ path: 'test-results/visual/home-new-desktop.png', fullPage: true });
  const detail = page.getByTestId('apartment-card').first().getByRole('link', { name: 'Chi tiết', exact: true });await detail.click();
  await expect(page.getByRole('link', { name: 'Đăng nhập để gửi yêu cầu thuê' })).toBeVisible();
  await page.goto('/');await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByTestId('apartment-card').first()).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/visual/home-new-mobile.png', fullPage: true });
  for (const icon of await page.locator('.home-icon').all()) expect(await icon.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  expect(errors).toEqual([]);
});
