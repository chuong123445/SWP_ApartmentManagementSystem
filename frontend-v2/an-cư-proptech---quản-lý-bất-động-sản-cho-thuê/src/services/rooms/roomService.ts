import type { NewRoom, Room, RoomStatus } from '@/types';
import { apiFetch } from '@/services/http/client';

interface ApiRoom {
  id: string;
  buildingId: string;
  roomNumber: string;
  floor: number | null;
  area: number | null;
  price: number | null;
  deposit?: number | null;
  status: string;
  amenities?: string[] | null;
  electricityIndex?: number | null;
  waterIndex?: number | null;
  maxOccupants?: number | null;
  legalDocumentCode?: string | null;
}

const roomStatuses: RoomStatus[] = ['available', 'rented', 'overdue', 'maintenance', 'expiring'];

export function fromApiRoom(data: ApiRoom): Room {
  const status = data.status?.toLowerCase() as RoomStatus;
  if (!data.id || !roomStatuses.includes(status)) {
    throw new Error('Dữ liệu phòng trả về từ máy chủ không hợp lệ.');
  }
  return {
    id: data.id,
    buildingId: data.buildingId,
    roomNumber: data.roomNumber,
    floor: data.floor ?? 1,
    area: data.area ?? 0,
    price: data.price ?? 0,
    deposit: data.deposit ?? undefined,
    status,
    amenities: data.amenities ?? [],
    electricityIndex: data.electricityIndex ?? 0,
    waterIndex: data.waterIndex ?? 0,
    maxOccupants: data.maxOccupants ?? 2,
    legalDocNumber: data.legalDocumentCode ?? undefined,
  };
}

export function toCreateRoomRequest(room: NewRoom) {
  // IDs are generated by JPA. Only send fields supported by the room API.
  return {
    buildingId: room.buildingId,
    roomNumber: room.roomNumber.trim(),
    floor: room.floor,
    area: room.area,
    price: room.price,
    deposit: room.deposit,
    status: room.status.toUpperCase(),
    amenities: room.amenities,
    electricityIndex: room.electricityIndex,
    waterIndex: room.waterIndex,
    maxOccupants: room.maxOccupants,
  };
}

async function requestRooms(url: string, options?: RequestInit) {
  let response: Response;
  try {
    response = await apiFetch(url, options);
  } catch {
    throw new Error('Không thể kết nối máy chủ. Vui lòng kiểm tra backend và thử lại.');
  }
  if (!response.ok) {
    const error = await response.json().catch(() => null);
    const detail = error?.detail || error?.message || error?.error;
    throw new Error(`Yêu cầu phòng thất bại (HTTP ${response.status}).${detail ? ` ${detail}` : ' Vui lòng kiểm tra backend và thử lại.'}`);
  }
  return response.json();
}

export async function getRooms(apiBaseUrl: string): Promise<Room[]> {
  const data = await requestRooms(`${apiBaseUrl}/rooms`);
  if (!Array.isArray(data)) {
    throw new Error('Danh sách phòng trả về từ máy chủ không hợp lệ.');
  }
  return data.map(fromApiRoom);
}

export async function createRoom(apiBaseUrl: string, room: NewRoom): Promise<Room> {
  const data = await requestRooms(`${apiBaseUrl}/rooms`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(toCreateRoomRequest(room)),
  });
  return fromApiRoom(data);
}
